import json
import os
import sys
import urllib.request
import urllib.error

API_URL = os.getenv("API_URL", "http://127.0.0.1:8000/api/measurements/")


def resolve_stream_file():
    """Resolves telemetry_stream.json inside simulator directory or from env override."""
    env_path = os.getenv("TELEMETRY_STREAM_FILE")
    if env_path and os.path.exists(env_path):
        return env_path
    return os.path.join(os.path.dirname(__file__), "telemetry_stream.json")


def post_measurement(packet):
    payload = {
        "device_id": packet["device_id"],
        "timestamp": packet["timestamp"],
        "air_temperature": packet["air_temperature"],
        "leaf_temperature": packet["leaf_temperature"],
        "soil_moisture": packet["soil_moisture"],
    }
    req = urllib.request.Request(
        API_URL,
        data=json.dumps(payload).encode("utf-8"),
        headers={"Content-Type": "application/json", "Accept": "application/json"},
        method="POST",
    )
    try:
        with urllib.request.urlopen(req, timeout=5) as response:
            return response.status
    except urllib.error.HTTPError as e:
        return e.code
    except urllib.error.URLError:
        return 0


def main():
    stream_file = resolve_stream_file()
    if not os.path.exists(stream_file):
        print(f"[-] Error: '{stream_file}' not found. Run ./simulator first.")
        sys.exit(1)

    with open(stream_file, "r") as f:
        packets = json.load(f)

    print(f"[*] Dispatching {len(packets)} telemetry packets to {API_URL}\n")
    print(f"{'#':<3} | {'Status':<10} | {'Result':<16} | Scenario")
    print("-" * 72)

    for idx, pkt in enumerate(packets, 1):
        status = post_measurement(pkt)
        expected = pkt.get("expected_status")
        match = "MATCH" if status == expected else f"EXPECTED {expected}"
        print(f"{idx:02d}  | HTTP {status:<4} | {match:<16} | {pkt['scenario_tag']}")

    print("-" * 72)
    print("[+] Bridge dispatch complete.\n")


if __name__ == "__main__":
    main()
